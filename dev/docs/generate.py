# The Rust items a `#[cfg(test)]` can take away. See `production` in
# crates/solium/src/script/reference.rs, which this matches line for line.
TEST_ITEMS = ("mod ", "fn ", "const ", "static ", "impl", "use ", "struct ", "enum ",
              "trait ", "type ", "thread_local!", "macro_rules!")


def production(path, text):
    """A source file with every line that is not production code blanked.

    Comment lines go, and in Rust every item under `#[cfg(test)]`, so a flag a
    test hands to the test runner is not cited as a place Solium reads it. The
    same cut the environment test makes.
    """
    rust = path.endswith(".rs")
    comment = "--" if path.endswith(".lua") else "//"
    lines = text.split("\n")
    kept = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if rust and line.strip() == "#[cfg(test)]":
            indent = line[:len(line) - len(line.lstrip())]
            item = index + 1
            while item < len(lines) and lines[item].lstrip().startswith("#["):
                item += 1
            head = lines[item].strip() if item < len(lines) else ""
            head = re.sub(r"^pub(\((crate|super)\))? ", "", head)
            if head.startswith(TEST_ITEMS):
                end = item
                while end < len(lines):
                    each = lines[end]
                    rest = each[len(indent):] if each.startswith(indent) else None
                    closes = (rest is not None and not rest[:1].isspace()
                              and rest.rstrip() in ("}", "};", "];", ");"))
                    first = each.rstrip()
                    # `mod tests;`, or `fn helper() {}` with its braces closed
                    # on the same line.
                    one_line = end == item and (first.endswith(";") or (
                        "{" in first and first.count("{") == first.count("}")))
                    if closes or one_line:
                        break
                    end += 1
                end = min(end, len(lines) - 1)
                kept.extend([""] * (end + 1 - index))
                index = end + 1
                continue
        kept.append("" if line.lstrip().startswith(comment) else line)
        index += 1
    return "\n".join(kept)


# Not a name a match arm answers (`=> "SOLIUM_QML"`): that labels a log line.
VARIABLE = re.compile(r'(?<!=> )"((?:SOLIUM_|XDG_|XCURSOR_)[A-Z0-9_]+|WAYLAND_DISPLAY|DISPLAY)"')
# A flag is read where it is compared: `== "--x"`, `Some("--x")`,
# `strip_prefix("--x")`, a match arm `"--x" =>`, or `const X: &str = "--x"`.
FLAG = re.compile(r'(?:==|!=|Some\(|strip_prefix\(|starts_with\(|&str =)\s*"(--[a-z][a-z-]*)"'
                  r'|"(--[a-z][a-z-]*)"(?=\s*(?:=>|\|))')


def reads():
    """Where production code reads each `"SOLIUM_..."`, `"--flag"` and named variable."""
    found = {}
    for part in ("src", "lua", "qml"):
        for directory, _, files in os.walk(os.path.join(ROOT, "crates/solium", part)):
            for name in sorted(files):
                if not name.endswith((".rs", ".lua", ".cpp", ".h", ".qml")):
                    continue
                full = os.path.join(directory, name)
                relative = os.path.relpath(full, ROOT)
                # The environment test's own file: its strings are the names it looks for.
                if relative == "crates/solium/src/script/reference.rs":
                    continue
                with open(full, encoding="utf-8") as file:
                    text = production(relative, file.read())
                matches = [(m.start(1), m.group(1)) for m in VARIABLE.finditer(text)]
                if relative.endswith(".rs"):
                    matches += [(m.start(1) if m.group(1) else m.start(2), m.group(1) or m.group(2))
                                for m in FLAG.finditer(text)]
                for at, found_name in sorted(matches):
                    found.setdefault(found_name, []).append((relative, text.count("\n", 0, at) + 1))
    return found


def environment(rev):
    lines = read(ENVIRONMENT).split("\n")
    where = reads()
    out = [
        "# Flags and environment",
        "",
        "Every command-line flag and `SOLIUM_*` variable the compositor reads, "
        f"from [`environment.txt`]({source_link(ENVIRONMENT, rev=rev)}), with "
        "where the code reads each one. A test fails when the code reads one "
        "this page does not list.",
        "",
    ]
    entry = None
    description_lines = []

    def flush():
        nonlocal entry
        if entry is None:
            return
        name, spelled = entry
        text = links.rewrite("\n".join(description_lines).strip(), ENVIRONMENT,
                             "generated/reference/environment.md")
        out.append(f"### `{spelled}` {{#{name.lstrip('-').lower().replace('_', '-')}}}")
        out.append("")
        out.append(text)
        sites = where.get(name, [])
        if sites:
            shown = ", ".join(f"[{posixpath.basename(path)}:{line}]({source_link(path, line, rev)})"
                              for path, line in sites[:6])
            more = f" and {len(sites) - 6} more" if len(sites) > 6 else ""
            out.extend(["", f"<small>Read at {shown}{more}.</small>"])
        out.append("")
        entry = None
        description_lines.clear()

    for line in lines:
        if line.startswith("#") and not line.startswith("## "):
            continue
        if line.startswith("## "):
            flush()
            out += [line, ""]
            continue
        if line.startswith("    "):
            description_lines.append(line[4:])
            continue
        if not line.strip():
            if entry is None:
                out.append("")
            else:
                description_lines.append("")
            continue
        match = re.match(r"^((?:--[a-z][a-z-]*)|(?:[A-Z][A-Z0-9_]*))(?=$|[ =])", line)
        if match and (match.group(1).startswith("--") or match.group(1).isupper()) and len(match.group(1)) > 2:
            flush()
            entry = (match.group(1), line.strip())
            continue
        flush()
        out.append(links.rewrite(line, ENVIRONMENT, "generated/reference/environment.md"))
    flush()
    write("generated/reference/environment.md", re.sub(r"\n{3,}", "\n\n", "\n".join(out)), ENVIRONMENT)


