HEADER = (
    "<!-- Generated by dev/docs/generate.py from {source}. "
    "Edit that, not this. -->\n\n"
)


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as file:
        return file.read()


def write(book_path, text, source):
    """Write one page of the book, under docs/."""
    path = os.path.join(DOCS, book_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as file:
        file.write(HEADER.format(source=source) + text.rstrip() + "\n")


def source_link(path, line=None, rev=None):
    """A link to a line of a file on GitHub."""
    # A line only means something in one commit; a file is best read as it is now.
    ref = (rev or links.BRANCH) if line else links.BRANCH
    url = f"{links.REPOSITORY}/blob/{ref}/{path}"
    return url + (f"#L{line}" if line else "")


def first_sentence(text, limit=180):
    """The first sentence of some prose, cut at a word if it runs long."""
    text = " ".join(text.split())
    match = re.search(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    if len(sentence) > limit:
        # An aside is the natural place to stop; a word boundary otherwise.
        aside = sentence.find(" -- ")
        cut = aside if 0 < aside <= limit else sentence[:limit].rfind(" ")
        sentence = sentence[:cut].rstrip(",;:") + " …"
    return sentence


