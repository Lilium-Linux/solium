def copies():
    for path in links.COPIED:
        destination = os.path.join(OUT, "repo", path)
        os.makedirs(os.path.dirname(destination), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, path), destination)


def sections(markdown):
    """A Markdown file cut at its `## ` headings: [(title or None, text)]."""
    out = [(None, [])]
    fenced = False
    for line in markdown.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
        if not fenced and line.startswith("## "):
            out.append((line[3:].strip(), [line]))
        else:
            out[-1][1].append(line)
    return [(title, "\n".join(lines)) for title, lines in out]


def readme():
    """The README, as the introduction and the Getting started page."""
    parts = sections(read(links.README))
    found = {title for title, _ in parts}
    missing = [title for title in links.INSTALL_SECTIONS if title not in found]
    if missing:
        sys.exit(f"generate: the README has no section called {missing}")

    introduction = "\n".join(text for title, text in parts if title not in links.INSTALL_SECTIONS)
    # Included by docs/introduction.md, so its links are written from there.
    write(
        "generated/readme/introduction.md",
        links.rewrite(introduction, links.README, links.INTRODUCTION),
        links.README,
    )

    install = "\n".join(text for title, text in parts if title in links.INSTALL_SECTIONS)
    wanted = ("The thirty-second version", "Where things live")
    first = [text for title, text in sections(read("docs/ricing.md")) if title in wanted]
    if len(first) != len(wanted):
        found = {title for title, _ in sections(read("docs/ricing.md"))}
        sys.exit(f"generate: docs/ricing.md has no section called "
                 f"{[title for title in wanted if title not in found]}")
    page = (
        "# Getting started\n\n"
        "Building Solium, running it, installing it, and a first configuration. "
        "The first three sections are the README's; the last two are the start "
        "of [Ricing Solium](../ricing.md), which goes on from there.\n\n"
        + links.rewrite(install, links.README, links.GETTING_STARTED)
        + "\n\n"
        + links.rewrite("\n\n".join(first), "docs/ricing.md", links.GETTING_STARTED)
    )
    write(links.GETTING_STARTED, page, "README.md and docs/ricing.md")


# config.lua ----------------------------------------------------------------


def comment_text(line):
    """A Lua comment line without its `--` and the one space after it."""
    text = line.strip()[2:]
    return text[1:] if text.startswith(" ") else text


def indent_of(text):
    return len(text) - len(text.lstrip(" "))


def looks_like_lua(block):
    return bool(re.search(r"[={}]|\bsol\.|\breturn\b|\bfunction\b", block))


def term_list(lines):
    """Aligned `term   description` lines as a Markdown list, or None.

    Only the simple shape: every entry starts at the block's indent, its
    description continues on more-indented lines, and nothing has columns of
    its own inside it. Anything else is kept as preformatted text by the
    caller, which is always faithful and only sometimes pretty.
    """
    base = indent_of(lines[0])
    items = []
    for line in lines:
        if not line.strip():
            continue
        indent = indent_of(line)
        body = line.strip()
        if indent == base:
            if body.startswith(("* ", "- ")):
                items.append(["", body[2:]])
                continue
            match = re.match(r"^(\S.*?)\s{2,}(\S.*)$", body)
            if not match:
                return None
            items.append([match.group(1), match.group(2)])
        elif indent > base and items and not re.search(r"\S\s{2,}\S", body):
            items[-1][1] += " " + body
        else:
            return None
    if not items:
        return None
    out = []
    for term, description in items:
        if not term:
            out.append(f"- {description}")
        elif "`" in term or " " in term and not re.match(r'^[\w."\'|=+-]+(\s*[|=,]\s*[\w."\'|=+-]+)*$', term):
            out.append(f"- **{term}**: {description}")
        else:
            out.append(f"- `{term}`: {description}")
    return "\n".join(out)


def prose(comment_lines):
    """Lua comment lines as Markdown.

    Indented four or more is an example, and becomes a code block. Indented two
    or three is an aligned list, which becomes a Markdown list when its shape is
    simple enough to read one from, and preformatted text when it is not.
    Everything else is prose, which in these files is already Markdown.
    """
    lines = [comment_text(line) for line in comment_lines]
    out = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if indent_of(line) >= 2 and line.strip():
            code = indent_of(line) >= 4
            block = []
            while index < len(lines):
                current = lines[index]
                if current.strip():
                    if indent_of(current) < 2:
                        break
                    block.append(current)
                    index += 1
                    continue
                # A blank line ends the block unless the next line carries on.
                following = next((later for later in lines[index + 1:] if later.strip()), "")
                if indent_of(following) >= (4 if code else 2):
                    block.append("")
                    index += 1
                    continue
                break
            while block and not block[-1].strip():
                block.pop()
            least = min(indent_of(each) for each in block if each.strip())
            dedented = "\n".join(each[least:] for each in block)
            listed = None if code else term_list(block)
            if listed:
                out.append("\n" + listed + "\n")
            else:
                language = "lua" if code and looks_like_lua(dedented) else "text"
                out.append(f"\n```{language}\n{dedented}\n```\n")
            continue
        # A heading would be read into a line that starts with `#`.
        out.append("\\" + line if line.startswith("#") else line)
        index += 1
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def depth_change(line):
    """How much a line of Lua opens or closes tables, strings and comments aside."""
    code = re.sub(r'"(\\.|[^"\\])*"', '""', line)
    code = code.split("--", 1)[0]
    return code.count("{") - code.count("}")


def chunks(body, indent):
    """A table body cut into (comment lines, code lines) at each comment.

    A blank line also ends a chunk, so settings the file keeps apart stay apart
    -- but not inside a table, whose own blank lines belong to it.
    """
    out = []
    comment, code = [], []
    depth = 0

    def flush():
        if comment or code:
            out.append((list(comment), list(code)))
        comment.clear()
        code.clear()

    for line in body:
        stripped = line.strip()
        if depth > 0:
            code.append(line)
            depth += depth_change(line)
            continue
        if not stripped:
            # A comment on its own, like "There is no dock.", ends here too.
            flush()
            continue
        if stripped.startswith("--") and indent_of(line) == indent:
            if code:
                flush()
            comment.append(line)
        else:
            code.append(line)
            depth += depth_change(line)
    flush()
    return out


def keys_of(code, indent):
    """The keys a chunk of settings sets, at this depth."""
    found = []
    for line in code:
        if indent_of(line) == indent:
            match = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
            if match:
                found.append(match.group(1))
    return found


def dedent(lines, amount):
    """Lines of a table body, moved left by the depth they sit at in the file."""
    return "\n".join(line[amount:] if line[:amount].strip() == "" else line.lstrip() for line in lines)


def parse_config():
    """config.lua as (header, [top-level entries], trailer)."""
    lines = read(CONFIG).split("\n")
    start = next(i for i, line in enumerate(lines) if line.startswith("local defaults = {"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i] == "}")
    header = [line for line in lines[:start] if line.startswith("--")]
    entries = []
    for comment, code in chunks(lines[start + 1:end], 4):
        keys = keys_of(code, 4)
        if not keys:
            entries.append({"key": None, "comment": comment, "code": []})
            continue
        entries.append({"key": keys[0], "comment": comment, "code": code})
    trailer = lines[end + 1:]
    if len([entry for entry in entries if entry["key"]]) < 10:
        sys.exit("generate: found fewer than ten settings in config.lua; the parse is broken")
    return header, entries, trailer


def value_summary(code):
    """A setting's default, short enough for a table cell."""
    first = code[0].split("=", 1)[1].strip().rstrip(",")
    if len(code) == 1:
        return first
    return "{ … }"


def configuration(rev):
    header, entries, trailer = parse_config()
    out = [
        "# Configuration",
        "",
        f"This page is [`config.lua`]({source_link(CONFIG, rev=rev)}), the file "
        "that sets every default, with its comments as the text and its settings "
        "as the code. To change a setting, write only that setting in "
        "`~/.config/solium/user.lua`; [Every setting](settings.md) is the index.",
        "",
        prose(header),
        "",
    ]
    for entry in entries:
        key = entry["key"]
        if key is None:
            out += [prose(entry["comment"]), ""]
            continue
        out += [f"## `{key}` {{#{key}}}", ""]
        if entry["comment"]:
            out += [prose(entry["comment"]), ""]
        code = entry["code"]
        body = code[1:-1] if len(code) > 1 and code[0].rstrip().endswith("{") else []
        if body and any(line.strip().startswith("--") for line in body):
            for comment, sub in chunks(body, 8):
                sub_keys = keys_of(sub, 8)
                if sub_keys:
                    anchors = "".join(f'<a id="{key}.{name}"></a>' for name in sub_keys[1:])
                    title = ", ".join(f"`{key}.{name}`" for name in sub_keys)
                    out += [f"### {title} {{#{key}.{sub_keys[0]}}}", ""]
                    if anchors:
                        out += [anchors, ""]
                if comment:
                    out += [prose(comment), ""]
                if sub:
                    out += ["The default:", "", "```lua", dedent(sub, 8), "```", ""]
        else:
            anchors = "".join(f'<a id="{key}.{name}"></a>' for name in keys_of(body, 8))
            if anchors:
                out += [anchors, ""]
            out += ["The default:", "", "```lua", dedent(code, 4), "```", ""]

    out += [
        "## How `user.lua` is read {#how-user-lua-is-read}",
        "",
        "The rest of `config.lua` is the code that merges your file over the "
        "defaults above and reports what it could not have meant. Its comments "
        "are the explanation; the code is folded under each.",
        "",
    ]
    block_comment, block_code = [], []

    def flush():
        if block_comment:
            out.extend([prose(block_comment), ""])
        code = "\n".join(block_code).strip("\n")
        if code:
            out.extend(["<details><summary>The code</summary>", "", "```lua", code, "```", "", "</details>", ""])
        block_comment.clear()
        block_code.clear()

    for line in trailer:
        if line.startswith("--"):
            if block_code and any(each.strip() for each in block_code):
                flush()
            block_comment.append(line)
        else:
            block_code.append(line)
    flush()
    write("generated/reference/configuration.md", "\n".join(out), CONFIG)
    return entries


def settings(entries):
    out = [
        "# Every setting",
        "",
        "One row for each top-level setting in `config.lua`, and each links to "
        "where [the configuration reference](configuration.md) explains it. A "
        "setting is written in `~/.config/solium/user.lua`, which holds only what "
        "you change:",
        "",
        "```lua",
        "return {",
        "    gap = 4,",
        "    tiling = { split = 0.618 },",
        "}",
        "```",
        "",
        "| Setting | Default | What it is |",
        "|---|---|---|",
    ]
    for entry in entries:
        key = entry["key"]
        if key is None:
            continue
        code = entry["code"]
        default = value_summary(code)
        text = first_sentence(" ".join(comment_text(line) for line in entry["comment"]
                                       if indent_of(comment_text(line)) < 2)) if entry["comment"] else ""
        body = code[1:-1] if len(code) > 1 and code[0].rstrip().endswith("{") else []
        sub_keys = keys_of(body, 8)
        if sub_keys:
            listed = ", ".join(f"[`{name}`](configuration.md#{key}.{name})" for name in sub_keys)
            text = (text + " " if text else "") + f"Keys: {listed}."
        cell = text.replace("|", "\\|")
        out.append(f"| [`{key}`](configuration.md#{key}) | `{default}` | {cell} |")
    write("generated/reference/settings.md", "\n".join(out), CONFIG)


# Bindings ----------------------------------------------------------------------


def normalise(combo):
    """`normalise_combo` in script.rs, which is what `--check` prints."""
    modifiers, key = set(), ""
    for part in combo.split("+"):
        part = part.strip().lower()
        if part in ("ctrl", "control"):
            modifiers.add("ctrl")
        elif part in ("alt", "meta"):
            modifiers.add("alt")
        elif part == "shift":
            modifiers.add("shift")
        elif part in ("super", "logo", "win", "cmd"):
            modifiers.add("super")
        elif part:
            key = part
    return "".join(f"{name}+" for name in ("ctrl", "alt", "shift", "super") if name in modifiers) + key


def check_output(solium):
    """What `solium --check` prints for the shipped configuration alone."""
    with tempfile.TemporaryDirectory() as home:
        environment = {
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
            "HOME": home,
            "XDG_CONFIG_HOME": os.path.join(home, "config"),
            "XDG_STATE_HOME": os.path.join(home, "state"),
            "RUST_LOG": "error",
        }
        result = subprocess.run(
            [solium, "--check"], env=environment, capture_output=True, text=True, timeout=120
        )
    if result.returncode != 0:
        sys.exit(f"generate: `solium --check` failed:\n{result.stdout}{result.stderr}")
    combos, expected = [], None
    for line in result.stdout.splitlines():
        match = re.match(r"^\s+ok: (\d+) binding", line)
        if match:
            expected = int(match.group(1))
            continue
        if expected is not None and line.startswith("    "):
            combos.append(line.split()[0])
        elif expected is not None and not line.startswith("    "):
            break
    if expected is None or len(combos) != expected:
        sys.exit(f"generate: could not read the bindings from `solium --check`:\n{result.stdout}")
    return combos


BIND = re.compile(r'^\s*(?:sol\.)?bind\(\s*"([^"]*)"\s*(\.\.\s*[A-Za-z_]\w*\s*)?,\s*(.*)$')


def handler_text(lines, index, rest):
    """What a binding calls, when it is short enough to show."""
    call = rest.rstrip()
    if call.endswith(")") and not re.match(r"^function\s*\([^)]*\)$", call):
        call = call[:-1].strip()
        inline = re.match(r"^function\s*\([^)]*\)\s*(.*?)\s*end$", call)
        return inline.group(1) if inline else call
    if re.match(r"^function\s*\([^)]*\)\s*$", call):
        body = []
        for later in lines[index + 1:]:
            if re.match(r"^\s*end\)\s*$", later):
                break
            body.append(later.strip())
        body = [each for each in body if each and not each.startswith("--")]
        if len(body) == 1:
            return body[0]
    return None


def comment_above(lines, index):
    """The comment just above a binding, skipping the bindings grouped with it."""
    at = index - 1
    while at >= 0 and BIND.match(lines[at]):
        at -= 1
    block = []
    while at >= 0 and lines[at].strip().startswith("--"):
        block.insert(0, comment_text(lines[at]))
        at -= 1
    text = " ".join(line for line in block if line.strip() and indent_of(line) < 2)
    return first_sentence(text) if text else None


def binding_sites():
    """Every `sol.bind` in the shipped Lua: literal ones, and `"prefix" .. n`."""
    sites = []
    for name in sorted(os.listdir(os.path.join(ROOT, LUA))):
        if not name.endswith(".lua"):
            continue
        path = f"{LUA}/{name}"
        lines = read(path).split("\n")
        for index, line in enumerate(lines):
            match = BIND.match(line)
            if not match or line.lstrip().startswith("local function"):
                continue
            sites.append({
                "file": name,
                "path": path,
                "line": index + 1,
                "combo": match.group(1),
                "template": bool(match.group(2)),
                "handler": handler_text(lines, index, match.group(3)),
                "comment": comment_above(lines, index),
            })
    return sites


def module_summary(path):
    lines = read(path).split("\n")
    head = []
    for line in lines:
        if not line.startswith("--"):
            break
        if not comment_text(line).strip():
            break
        head.append(comment_text(line))
    return first_sentence(" ".join(head)) if head else ""


def bindings(solium, rev):
    combos = check_output(solium)
    sites = binding_sites()
    literal = {normalise(site["combo"]): site for site in sites if not site["template"]}
    rows = {}
    unmatched = []
    for combo in combos:
        site = literal.get(combo)
        shown = site["combo"] if site else None
        if site is None:
            key = combo.split("+")[-1]
            for candidate in sites:
                if candidate["template"] and normalise(candidate["combo"] + key) == combo:
                    site, shown = candidate, candidate["combo"] + key
                    break
        if site is None:
            unmatched.append(combo)
            continue
        rows.setdefault((site["path"], site["line"]), (site, []))[1].append(shown)

    out = [
        "# Key bindings",
        "",
        f"The {len(combos)} bindings the shipped configuration makes, as "
        "`solium --check` lists them, with where each is made and what it calls. "
        "None of them belongs to the compositor: each is a `sol.bind` call in a "
        "script, so any of them can be changed or removed from the `bindings` "
        "section of `user.lua` ([how](configuration.md#bindings)), and "
        "`solium --check` then lists what your configuration replaced or removed.",
        "",
        "Two chords are the compositor's own and are not listed: `ctrl+alt+backspace` "
        "ends the session whatever the configuration says, except while the screen "
        "is locked, and `ctrl+alt+F1` to `ctrl+alt+F12` switch virtual terminal.",
        "",
        "Nor is a key a mode binds only while it is up, because `solium --check` "
        "lists what the configuration binds as it loads: `escape` leaves the "
        "overview, and is bound only while the overview is open, so that the rest "
        "of the time it reaches the application with the keyboard.",
        "",
    ]
    by_file = {}
    for (path, line), (site, shown) in sorted(rows.items(), key=lambda item: (item[0][0] != f"{LUA}/init.lua", item[0])):
        by_file.setdefault(path, []).append((site, shown))
    for path, entries in by_file.items():
        name = posixpath.basename(path)
        out += [f"## {name}", ""]
        summary = module_summary(path)
        if summary:
            out += [summary, ""]
        out += ["| Keys | What it does | Where |", "|---|---|---|"]
        for site, shown in entries:
            if len(shown) > 2:
                keys = f"`{shown[0]}` … `{shown[-1]}`"
            else:
                keys = ", ".join(f"`{combo}`" for combo in shown)
            what = []
            if site["handler"]:
                what.append(f"`{site['handler']}`")
            if site["comment"]:
                what.append(site["comment"])
            cell = " — ".join(what).replace("|", "\\|")
            where = f"[{name}:{site['line']}]({source_link(path, site['line'], rev)})"
            out.append(f"| {keys} | {cell} | {where} |")
        out.append("")
    if unmatched:
        out += ["## Made elsewhere", "",
                "Bound, but not by a `sol.bind` call this page could find:", ""]
        out += [f"- `{combo}`" for combo in unmatched]
    write("generated/reference/bindings.md", "\n".join(out), "`solium --check` and crates/solium/lua")


