def parse_sol():
    """sol.lua as declarations, each with its `---` block."""
    lines = read(SOL_LUA).split("\n")
    header = []
    for line in lines[1:]:
        if line.startswith("---"):
            break
        if line.startswith("--"):
            header.append(line)
        elif header and not line.strip():
            break
    items, doc = [], []
    for number, line in enumerate(lines, 1):
        if line.startswith("---@meta"):
            continue
        if line.startswith("---"):
            doc.append(line[3:])
            continue
        if not doc:
            continue
        block, doc = doc, []
        item = {"doc": block, "line": number}
        function = re.match(r"^function ([\w.:]+)\((.*)\)", line)
        field = re.match(r"^(sol\.\w+) = ", line)
        tags = [each for each in block if each.startswith("@")]
        if function:
            item.update(kind="function", name=function.group(1),
                        params=[p.strip() for p in function.group(2).split(",") if p.strip()])
        elif field:
            item.update(kind="field", name=field.group(1))
        elif any(tag.startswith("@class") for tag in tags):
            name = next(tag.split()[1] for tag in tags if tag.startswith("@class"))
            item.update(kind="class", name=name.rstrip(":"))
        elif any(tag.startswith("@alias") for tag in tags):
            name = next(tag.split()[1] for tag in tags if tag.startswith("@alias"))
            item.update(kind="alias", name=name)
        else:
            continue
        items.append(item)
    return header, items


def description(block):
    """The prose of a `---` block: every line that is not a tag."""
    text, lines = [], []
    for line in block:
        if line.startswith("@") or line.startswith("|"):
            if lines:
                text.append(" ".join(lines))
                lines = []
            continue
        if line.strip():
            lines.append(line.strip())
        elif lines:
            text.append(" ".join(lines))
            lines = []
    if lines:
        text.append(" ".join(lines))
    return "\n\n".join(text)


def type_link(kinds, text):
    """A LuaLS type, in code, with the classes and aliases it names linked."""
    parts = re.split(r"(sol\.[A-Z]\w*|\bTree\b|\bScroller\b)", text)
    out = []
    for index, part in enumerate(parts):
        if not part:
            continue
        name = {"Tree": "sol.Tree", "Scroller": "sol.Scroller"}.get(part, part)
        if index % 2 and name in kinds:
            out.append(f"[`{part}`](#{kinds[name]})")
        else:
            out.append(f"`{part}`" if part.strip() else part)
    return "".join(out)


def tag_parts(tag):
    """`@param name type description` as (name, type, description).

    The type ends at the first space that is not inside braces, brackets or
    parentheses, which is enough for every type this file writes.
    """
    rest = tag.split(None, 1)[1] if " " in tag else ""
    if tag.startswith(("@param", "@field")):
        name, _, rest = rest.partition(" ")
    else:
        name = ""
    depth, end = 0, len(rest)
    for index, char in enumerate(rest):
        if char in "({[<":
            depth += 1
        elif char in ")}]>":
            depth -= 1
        elif char == " " and depth == 0 and not rest[:index].endswith((",", ":", "|")) \
                and not rest[index + 1:index + 2] in ("|",):
            end = index
            break
    return name, rest[:end].strip(), rest[end:].strip()


def overload_line(kinds, name, overload):
    """`fun(a: T): R`, written as the call it describes."""
    if not overload.startswith("fun("):
        return type_link(kinds, overload)
    depth = 0
    for index, char in enumerate(overload[3:], 3):
        depth += {"(": 1, ")": -1}.get(char, 0)
        if depth == 0:
            break
    arguments = overload[4:index]
    result = overload[index + 1:].lstrip(":").strip()
    line = f"`{name}({arguments})`"
    return line + (f" returns {type_link(kinds, result)}" if result else "")


def lua_api(rev):
    header, items = parse_sol()
    kinds = {}
    for item in items:
        if item["kind"] in ("class", "alias"):
            kinds[item["name"]] = "type-" + item["name"].replace(".", "-").lower()
    # A tree and a strip have sections of their own, which is where they link.
    kinds["sol.Tree"] = "tree"
    kinds["sol.Scroller"] = "scroller"
    kinds["sol.Event"] = "events"

    def function_entry(item):
        tags = [each for each in item["doc"] if each.startswith("@")]
        params = {name.rstrip("?"): (kind + ("?" if name.endswith("?") else ""), text)
                  for name, kind, text in (tag_parts(tag) for tag in tags if tag.startswith("@param"))}
        returns = [tag_parts(tag) for tag in tags if tag.startswith("@return")]
        overloads = [tag.split(None, 1)[1] for tag in tags if tag.startswith("@overload")]
        name = item["name"]
        signature = f"{name}({', '.join(item['params'])})"
        anchor = name.replace(".", "-").replace(":", "-").lower()
        out = [f"### `{signature}` {{#{anchor}}}", ""]
        text = description(item["doc"])
        if text:
            out += [text, ""]
        if overloads:
            out += ["Also called as:", ""]
            short = name.split(":")[-1] if ":" in name else name
            out += [f"- {overload_line(kinds, short, overload)}" for overload in overloads]
            out.append("")
        if item["params"]:
            out += ["Parameters:", ""]
            for param in item["params"]:
                kind, text = params.get(param, ("", ""))
                optional = kind.endswith("?") or param.endswith("?")
                line = f"- `{param}`" + (f": {type_link(kinds, kind.rstrip('?'))}" if kind else "")
                if optional:
                    line += " (optional)"
                if text:
                    line += f" — {text}"
                out.append(line)
            out.append("")
        shown = [(kind, text) for _, kind, text in returns if kind and kind != "nil"]
        if shown:
            out += ["Returns " + "; ".join(
                type_link(kinds, kind) + (f" ({text})" if text else "") for kind, text in shown) + ".", ""]
        out.append(f"<small>[sol.lua:{item['line']}]({source_link(SOL_LUA, item['line'], rev)})</small>")
        out.append("")
        return out

    def type_entry(item):
        tags = [each for each in item["doc"] if each.startswith("@")]
        name = item["name"]
        out = [f"### `{name}` {{#{kinds[name]}}}", ""]
        text = description(item["doc"])
        if text:
            out += [text, ""]
        head = next((tag for tag in tags if tag.startswith("@class")), "")
        if ":" in head:
            parent = head.split(":", 1)[1].strip()
            out += [f"Has every field of {type_link(kinds, parent)}, and:", ""]
        fields = [tag_parts(tag) for tag in tags if tag.startswith("@field")]
        for field, kind, text in fields:
            optional = field.endswith("?")
            line = f"- `{field.rstrip('?')}`: {type_link(kinds, kind)}"
            if optional:
                line += " (optional)"
            if text:
                line += f" — {text}"
            out.append(line)
        values = [line for line in item["doc"] if line.startswith("|")]
        for value in values:
            value = value[1:].strip()
            shown, _, text = value.partition(" # ")
            out.append(f"- {type_link(kinds, shown.strip())}" + (f" — {text.strip()}" if text else ""))
        if fields or values:
            out.append("")
        return out

    functions = [item for item in items if item["kind"] == "function"]
    fields = [item for item in items if item["kind"] == "field"]
    public_fields = [item for item in fields if not item["name"].startswith("sol._") and item["name"] != "sol.layout"]
    private = [item for item in fields if item["name"].startswith("sol._")]
    types = [item for item in items if item["kind"] in ("class", "alias")
             and item["name"] not in ("sol", "sol.layout", "sol.Event")]
    events = next(item for item in items if item["name"] == "sol.Event")

    count = len(functions) + len(fields)
    out = [
        "# The Lua API",
        "",
        "Everything the compositor puts in the `sol` table, transcribed from "
        f"[`sol.lua`]({source_link(SOL_LUA)}), the definitions file "
        "lua-language-server reads for completion ([how to set it up](../../ricing.md#editor-completion)). "
        f"A test fails when the compositor and that file disagree about any of its {count} names.",
        "",
        "Most calls queue a command and return nothing. The commands a handler "
        "queues are applied together when it returns, in the order it queued "
        "them, and every animated one uses the timing `sol.animate` last set in "
        "that handler. [Desktop modes](../../modes.md) is the guide to using them.",
        "",
        "## Events {#events}",
        "",
        description(events["doc"]) or "What `sol.on` can listen for.",
        "",
        "| Event | Handler arguments and meaning |",
        "|---|---|",
    ]
    for value in (line for line in events["doc"] if line.startswith("|")):
        shown, _, text = value[1:].strip().partition(" # ")
        out.append(f"| `{shown.strip().strip(chr(34))}` | {text.strip().replace('|', chr(92) + '|')} |")
    out += ["", "## `sol` {#sol}", ""]
    for item in functions:
        if item["name"].startswith("sol.") and not item["name"].startswith("sol.layout."):
            out += function_entry(item)
    for item in public_fields:
        anchor = item["name"].replace(".", "-").lower()
        out += [f"### `{item['name']}` {{#{anchor}}}", "", description(item["doc"]), ""]
    out += ["## `sol.layout` {#sol-layout}", "",
            description(next(item for item in items if item["name"] == "sol.layout")["doc"]), ""]
    for item in functions:
        if item["name"].startswith("sol.layout."):
            out += function_entry(item)
    for prefix, title, anchor, cls in (("Tree:", "A dwindle tree", "tree", "sol.Tree"),
                                       ("Scroller:", "A scrolling strip", "scroller", "sol.Scroller")):
        out += [f"## {title} {{#{anchor}}}", ""]
        doc = next(item for item in items if item["name"] == cls)
        out += [description(doc["doc"]), ""]
        for item in functions:
            if item["name"].startswith(prefix):
                out += function_entry(item)
    out += ["## Types {#types}", "",
            "The shapes of the tables the calls above take and return.", ""]
    for item in types:
        if item["name"] in ("sol.Tree", "sol.Scroller"):
            continue
        out += type_entry(item)
    out += ["## Internal {#internal}", "",
            "Tables the compositor keeps in `sol` for its own use. They are listed "
            "so the list is complete; a script should use the functions named.", ""]
    for item in private:
        out += [f"- `{item['name']}` — {description(item['doc'])}"]
    text = "\n".join(out)
    write("generated/reference/lua-api.md", text, SOL_LUA)
    return count


